#!/usr/bin/env python3
"""Regenerates Sources/SwiftTerm/WcwidthData.swift, the per-code-point
widths that programs measure with instead of grapheme clusters.

  regen_wcwidth_data.py dump-libc OUT        # on Linux: glibc wcwidth(3)
  regen_wcwidth_data.py dump-utf8proc OUT    # on macOS with Homebrew utf8proc
  cc -o dump_wcwidth scripts/dump_wcwidth.c && ./dump_wcwidth en_US.UTF-8 > DARWIN   # on macOS
  regen_wcwidth_data.py generate GLIBC UTF8PROC DARWIN > Sources/SwiftTerm/WcwidthData.swift

glibc's table is what bash, zsh, mosh-server and Debian/Ubuntu tmux measure
with on Linux. utf8proc is what Homebrew's tmux links, and macOS's libc what
a shell or mosh-server on a Mac measures with; for those two only where they
differ from glibc is stored.
"""
import ctypes
import ctypes.util
import locale
import sys


def dump_libc(out):
    locale.setlocale(locale.LC_ALL, 'en_US.UTF-8')
    libc = ctypes.CDLL(ctypes.util.find_library('c'))
    with open(out, 'w') as f:
        for cp in range(0x110000):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            f.write('%X %d\n' % (cp, libc.wcwidth(cp)))


def dump_utf8proc(out):
    lib = ctypes.CDLL('/opt/homebrew/opt/utf8proc/lib/libutf8proc.dylib')
    lib.utf8proc_charwidth.restype = ctypes.c_int
    lib.utf8proc_category.restype = ctypes.c_int
    with open(out, 'w') as f:
        for cp in range(0x110000):
            if 0xD800 <= cp <= 0xDFFF or lib.utf8proc_category(cp) == 0:  # 0 = unassigned
                continue
            f.write('%X %d\n' % (cp, lib.utf8proc_charwidth(cp)))


def load(path):
    table = {}
    for line in open(path):
        cp, width = line.split()
        table[int(cp, 16)] = int(width)
    return table


def ranges(pred):
    out, start = [], None
    for cp in range(0x110001):
        if cp <= 0x10FFFF and pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, doc, rs):
    print('    /// %s' % doc)
    print('    static let %s: [Range] = [' % name)
    for lo, hi in rs:
        print('        Range(lo: 0x%04X, hi: 0x%04X),' % (lo, hi))
    print('    ]')
    print()


def generate(glibc_path, utf8proc_path, darwin_path):
    glibc, utf8proc, darwin = load(glibc_path), load(utf8proc_path), load(darwin_path)

    def drawn(table, cp):
        # wcwidth -1 (unassigned) is drawn one column wide
        width = table.get(cp, -1)
        return 1 if width < 0 else width

    def libc(cp):
        return drawn(glibc, cp)

    print('// This file is generated by scripts/regen_wcwidth_data.py from glibc 2.41')
    print('// wcwidth(3), utf8proc 2.11 utf8proc_charwidth and macOS 27 wcwidth(3).')
    print('// Do not edit by hand.')
    print('struct WcwidthData {')
    print('    typealias Range = UnicodeUtil.LH')
    print()
    emit('glibcZero', 'Printable code points glibc measures 0 columns wide',
         ranges(lambda cp: cp >= 0xA0 and glibc.get(cp) == 0))
    emit('glibcWide', 'Code points glibc measures 2 columns wide',
         ranges(lambda cp: glibc.get(cp) == 2))
    for width, name in ((0, 'utf8procZero'), (1, 'utf8procNarrow'), (2, 'utf8procWide')):
        emit(name, 'Code points utf8proc measures %d columns wide where glibc does not' % width,
             ranges(lambda cp, width=width: cp >= 0xA0 and cp in utf8proc and utf8proc[cp] == width and libc(cp) != width))
    for width, name in ((0, 'darwinZero'), (1, 'darwinNarrow'), (2, 'darwinWide')):
        emit(name, 'Code points macOS wcwidth measures %d columns wide where glibc does not' % width,
             ranges(lambda cp, width=width: cp >= 0xA0 and drawn(darwin, cp) == width and libc(cp) != width))
    print('}')


if __name__ == '__main__':
    if sys.argv[1] == 'dump-libc':
        dump_libc(sys.argv[2])
    elif sys.argv[1] == 'dump-utf8proc':
        dump_utf8proc(sys.argv[2])
    else:
        generate(sys.argv[2], sys.argv[3], sys.argv[4])
